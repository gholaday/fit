// Inline drizzle-kit's SQL migrations into a TS module so Metro needs no .sql loader.
import { readFileSync, writeFileSync } from 'node:fs';

const journal = JSON.parse(readFileSync('drizzle/meta/_journal.json', 'utf8'));
const entries = journal.entries.map((e) => {
  const key = `m${String(e.idx).padStart(4, '0')}`;
  const sql = readFileSync(`drizzle/${e.tag}.sql`, 'utf8');
  return `    ${key}: ${JSON.stringify(sql)},`;
});

writeFileSync(
  'src/migrations.ts',
  `// Generated by scripts/bundle-migrations.mjs from drizzle/. Do not edit.\n` +
    `export const migrations = {\n  journal: ${JSON.stringify(journal)},\n  migrations: {\n${entries.join('\n')}\n  },\n};\n`,
);
